#!/usr/bin/env python3
"""Builds the engine for FFI front ends: the UniFFI crate in FFI/ with the Rust engine in Engine/
(libmailstream.dylib on macOS, mailstream.dll on Windows, libmailstream.so on Linux), the
mailstream command line (target/<config>/mailstream, which the Flutter app bundles on macOS
and Linux), on macOS the Apple Intelligence tagger (target/<config>/mailstream-apple-tagger,
bundled beside it) and, with DART_OUT=<dir>, the Dart bindings into <dir>.
CONFIG=debug|release (default: debug).

The library and the command line come from one cargo run in the repository's workspace (MS-279),
into its one `target/`, where GPUI and the engine's tests find the same dependencies built. On
Linux it runs itself in `devenv shell`, whose fontconfig the FFI crate links through Blitz
(devenv.nix; without it the build stops at `yeslogic-fontconfig-sys`, MS-294).

The Dart bindings are one file per crate (MS-238): `mailstream.dart` for the FFI crate's methods
and `mailstream_engine.dart` for the engine's records (what commands answer), plus uniffi-dart's
`uniffi_runtime.dart`. Both crate files declare the converters they use (`FfiConverterUInt32`,
…), so `bindings.dart`, written here, exports both and hides the engine file's copies of names
the FFI file declares too."""
import os
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.dont_write_bytecode = True
from repo import ROOT, build_env, capped  # noqa: E402

CONFIG = os.environ.get("CONFIG", "debug")
LIBRARY = {"win32": "mailstream.dll", "darwin": "libmailstream.dylib"}.get(sys.platform, "libmailstream.so")
PROFILE = ["--release"] if CONFIG == "release" else []
# Without SDKROOT, CPATH and the like on macOS, which rebuilt C crates in every checkout (repo.py).
ENV = build_env()


def cargo(*args):
    subprocess.run(capped(["cargo", *args]), cwd=ROOT, check=True, env=ENV)


def main():
    if sys.platform == "linux" and "DEVENV_ROOT" not in os.environ:
        env = dict(ENV)
        if env.get("DART_OUT"):
            env["DART_OUT"] = str(Path(env["DART_OUT"]).resolve())
        command = ["devenv", "shell", "--", "python3", str(Path(__file__).resolve())]
        sys.exit(subprocess.run(command, cwd=ROOT, env=env).returncode)
    cargo("build", *PROFILE, "-p", "mailstream", "-p", "mailstream-engine", "--lib", "--bins")
    print(f"Built target/{CONFIG}/{LIBRARY} and target/{CONFIG}/mailstream", flush=True)
    if sys.platform == "darwin":
        tagger = ROOT / f"target/{CONFIG}/mailstream-apple-tagger"
        subprocess.run([sys.executable, str(ROOT / "scripts/apple-tagger.py"), str(tagger)], check=True)
        print(f"Built {tagger.relative_to(ROOT)}", flush=True)
    if os.environ.get("DART_OUT"):
        out = Path(os.environ["DART_OUT"])
        cargo("run", "-q", "-p", "mailstream-bindgen", "--", f"target/{CONFIG}/{LIBRARY}",
              "--out-dir", str(out))
        write_exports(out)


# A public declaration of a generated Dart file: a class, enum, typedef or extension, a function,
# or a constant.
DECLARATION = re.compile(
    r"(?:(?:abstract|sealed|final|base) )*(?:class|enum|mixin|typedef|extension) ([A-Za-z]\w*)"
    r"|(?:external )?[\w<>?, ]+ (?!Function\()([A-Za-z]\w*)\("
    r"|(?:const|final|var) (?:[\w<>?]+ )?([A-Za-z]\w*) ="
)


def top_level(file):
    """The public names `file` declares outside any braces."""
    names, depth = set(), 0
    for line in file.read_text().splitlines():
        if depth == 0 and (match := DECLARATION.match(line)):
            names.update(name for name in match.groups() if name)
        depth += line.count("{") - line.count("}")
    return names


def write_exports(out):
    """`bindings.dart`: both crates' files, without the engine file's copies of names the FFI
    file declares too (an export of both would be ambiguous)."""
    shared = sorted(top_level(out / "mailstream.dart") & top_level(out / "mailstream_engine.dart"))
    hidden = f" hide {', '.join(shared)}" if shared else ""
    (out / "bindings.dart").write_text(
        "// Generated by scripts/ffi.py: both crates' bindings, without the engine file's copies of\n"
        "// the converters and functions the FFI file declares too.\n"
        "export 'mailstream.dart';\n"
        f"export 'mailstream_engine.dart'{hidden};\n"
    )


if __name__ == "__main__":
    try:
        main()
    except subprocess.CalledProcessError as error:
        sys.exit(error.returncode)
